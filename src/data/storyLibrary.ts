/**
 * 动态生成剧情
 * 根据世界观、性格画像、答题特质分布，从片段库中动态组合
 * 开场通过"氛围修饰器 × 开场模板"的组合，确保每次生成的开场都独一无二
 */
export function generateDynamicStory(params: {
  worldviewId: string;
  profile: { primaryTrait: PersonalityTrait; secondaryTrait: PersonalityTrait; traitScores: Record<PersonalityTrait, number> };
  episodesSurvived: number;
  episodeMax?: number;
}): {
  story: string[];
  ending: string;
  personalityAnalysis: string;
} {
  const lib = STORY_LIBRARIES[params.worldviewId] ?? CULTIVATION_STORY;
  const { primaryTrait, secondaryTrait } = params.profile;

  // 开场：氛围修饰器 + 随机开场模板，双重随机确保唯一性
  const atmosphere = pick(lib.openingAtmospheres);
  const openingTemplate = pick(lib.openings).text;
  const opening = `${atmosphere}${openingTemplate}`;

  // 中段：根据主特质选，次特质有 40% 概率插入
  const midSegments = [...lib.midByTrait[primaryTrait]];
  if (Math.random() < 0.4 && secondaryTrait !== primaryTrait) {
    const secondarySeg = pick(lib.midByTrait[secondaryTrait]);
    // 随机位置插入
    const insertPos = Math.floor(Math.random() * (midSegments.length + 1));
    midSegments.splice(insertPos, 0, secondarySeg);
  }
  // 取前 2 段作为中段
  const mid1 = midSegments[0].text;
  const mid2 = midSegments[1] ? midSegments[1].text : pick(lib.midByTrait[primaryTrait]).text;

  // 结局：根据存活集数选择类型
  // 阈值按世界观集数上限等比例设定（高 ≥ 75%，中 ≥ 62.5%），
  // 兼容不同世界观（深宫 80 / 末日 24 / 修仙 120），保持三档流量大致均衡
  const episodes = params.episodesSurvived;
  const max = params.episodeMax ?? 80;
  const highThreshold = Math.round(max * 0.75);
  const midThreshold = Math.round(max * 0.625);
  let endingPool: string[];
  if (episodes >= highThreshold) endingPool = lib.endings.high;
  else if (episodes >= midThreshold) endingPool = lib.endings.mid;
  else endingPool = lib.endings.low;

  const baseEnding = pick(endingPool).replace('{episodes}', String(episodes));
  const traitEnding = lib.endings.byTrait[primaryTrait] ?? '';
  const ending = `${baseEnding} ${traitEnding}`;

  // 性格分析
  const personalityAnalysis = pick(lib.personalityAnalysis[primaryTrait]);

  return {
    story: [opening, mid1, mid2],
    ending,
    personalityAnalysis,
  };
}

function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

/**
 * 生成单个抉择的后果叙事（沉浸式剧情演绎）
 * 根据世界观 + 用户选择的特质，从 midByTrait 模板中生成一段"因为你的选择，发生了..."的叙事
 * 不再判定对错，而是让用户体验选择带来的故事后果
 */
export function generateConsequence(params: {
  worldviewId: string;
  selectedTrait: PersonalityTrait;
  sceneText?: string;
  actionText?: string;
}): string {
  const lib = STORY_LIBRARIES[params.worldviewId] ?? CULTIVATION_STORY;
  const segments = lib.midByTrait[params.selectedTrait] ?? lib.midByTrait.cautious;
  const template = pick(segments).text;

  // 如果有场景和行动文本，拼一个过渡句让叙事更连贯
  if (params.actionText) {
    return `你选择了「${params.actionText}」。${template}`;
  }
  return template;
}

/**
 * 生成剧情开篇
 * 根据出身背景生成差异化开篇，让"先天随机"的出身真正影响叙事体验
 */
export function generateOpening(worldviewId: string, originSetup?: OriginSetup | null): string {
  const lib = STORY_LIBRARIES[worldviewId] ?? CULTIVATION_STORY;
  const atmosphere = pick(lib.openingAtmospheres);
  const openingTemplate = pick(lib.openings).text;
  const baseOpening = `${atmosphere}${openingTemplate}`;

  // 无出身设定时，使用通用开篇
  if (!originSetup) return baseOpening;

  // 拼接出身背景介绍，让玩家感受到"这是我的出身"
  const bg = originSetup.background;
  const talents = originSetup.talents
    .map((t) => `「${t.name}」`)
    .join('、');

  return `${baseOpening}\n\n你的身份是${bg.name}。${bg.description}\n\n与生俱来的天赋：${talents}。这些先天的条件，将与你后续的每一次抉择交织，共同书写你的命运。`;
}
