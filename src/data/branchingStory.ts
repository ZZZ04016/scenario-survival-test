export const BRANCHING_STORIES: Record<string, BranchScene[]> = {
  palace: PALACE_SCENES,
  apocalypse: APOCALYPSE_SCENES,
  cultivation: CULTIVATION_SCENES,
};

/**
 * 每个初始性格倾向对应的选项偏好顺序（取前 4 个特质对应的选项）。
 * 不同性格的玩家进入同一幕时，会看到完全不同的 4 个选项组合，
 * 从而让「选择性格」真正影响后续剧情走向，增强角色扮演感。
 */
const TRAIT_CHOICE_PREFERENCE: Record<PersonalityTrait, PersonalityTrait[]> = {
  cautious: ['cautious', 'scheming', 'loyal', 'decisive'],
  decisive: ['decisive', 'ambitious', 'scheming', 'cautious'],
  scheming: ['scheming', 'ambitious', 'cautious', 'decisive'],
  kind: ['kind', 'loyal', 'decisive', 'cautious'],
  ambitious: ['ambitious', 'decisive', 'scheming', 'cautious'],
  loyal: ['loyal', 'kind', 'decisive', 'cautious'],
};

/**
 * 根据玩家的初始性格倾向，从场景的选项池中挑选 4 个最契合的选项。
 * 若偏好列表中的选项不足 4 个，则用剩余选项兜底补齐。
 */
export function selectChoicesForTrait(
  scene: BranchScene,
  trait: PersonalityTrait,
): BranchChoice[] {
  const preference = TRAIT_CHOICE_PREFERENCE[trait] ?? TRAIT_CHOICE_PREFERENCE.cautious;
  const selected: BranchChoice[] = [];

  for (const preferredTrait of preference) {
    const choice = scene.choices.find((c) => c.trait === preferredTrait);
    if (choice) {
      selected.push(choice);
    }
    if (selected.length >= 4) break;
  }

  // 兜底：用剩余选项补齐到 4 个
  if (selected.length < 4) {
    for (const choice of scene.choices) {
      if (!selected.find((s) => s.id === choice.id)) {
        selected.push(choice);
      }
      if (selected.length >= 4) break;
    }
  }

  return selected;
}

export function getBranchScenes(
  worldviewId: string,
  trait?: PersonalityTrait,
): BranchScene[] {
  const scenes = BRANCHING_STORIES[worldviewId] ?? CULTIVATION_SCENES;
  if (!trait) return scenes;
  // 根据初始性格倾向，为每一幕筛选出 4 个最契合的选项
  return scenes.map((scene) => ({
    ...scene,
    choices: selectChoicesForTrait(scene, trait),
  }));
}
